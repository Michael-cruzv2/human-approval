-- ---------------------------------------------------------------
-- 10. View the mailer reads: everything that passes the DB-side gates.
--     The mailer still re-checks at send time (suppression, window, daily cap, domain).
-- ---------------------------------------------------------------
CREATE VIEW v_ready_to_queue AS
SELECT l.id AS lead_id, d.id AS draft_id, l.email AS to_email, l.domain, l.country, l.timezone,
       l.antispam_tag, d.subject, d.body_text, d.approved_hash
FROM leads l
JOIN drafts d ON d.lead_id = l.id
WHERE l.human_approval = 'APPROVED'
  AND l.agent_approval = 'VERIFIED'
  AND l.email IS NOT NULL
  AND l.archived = false
  AND d.human_approval = 'APPROVED'
  AND d.approved_hash = d.content_hash
  AND NOT EXISTS (SELECT 1 FROM email_sends s WHERE s.lead_id = l.id)
  AND NOT EXISTS (SELECT 1 FROM suppressions x
                  WHERE (x.kind = 'EMAIL'  AND x.value = lower(l.email))
                     OR (x.kind = 'DOMAIN' AND x.value = l.domain));

COMMIT;
