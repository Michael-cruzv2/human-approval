-- Lead automation: PostgreSQL schema (Neon). Draft v1, 2026-11-07.
-- One table per concern. Row-level security / roles are left to you.
-- Column ownership (who should write what) is noted in comments.

BEGIN;

-- ---------------------------------------------------------------
-- Shared helpers
-- ---------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------
-- 1. users  (max ~3: admin + operators)
-- ---------------------------------------------------------------
CREATE TABLE users (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email       text NOT NULL UNIQUE,
  name        text NOT NULL,
  role        text NOT NULL DEFAULT 'operator' CHECK (role IN ('admin', 'operator')),
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_users_updated BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------
-- 2. ls_runs  (LeadSearch run log + run lock)
--    Owner: LeadSearch
-- ---------------------------------------------------------------
CREATE TABLE ls_runs (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  status            text NOT NULL DEFAULT 'RUNNING'
                      CHECK (status IN ('RUNNING', 'COMPLETED', 'STOPPED', 'FAILED')),
  stop_reason       text,            -- e.g. TARGET_REACHED, SERPER_CAP, ALREADY_RUNNING, DB_UNAVAILABLE
  serper_used       integer NOT NULL DEFAULT 0,
  firecrawl_used    integer NOT NULL DEFAULT 0,
  candidates_found  integer NOT NULL DEFAULT 0,
  verified_count    integer NOT NULL DEFAULT 0,
  review_count      integer NOT NULL DEFAULT 0,
  rejected_count    integer NOT NULL DEFAULT 0,
  prefiltered_out   integer NOT NULL DEFAULT 0,
  avg_new_domains_per_query numeric(6,2),   -- saturation signal
  saturated         boolean NOT NULL DEFAULT false,
  mock              boolean NOT NULL DEFAULT false,
  serper_cap        integer,
  firecrawl_cap     integer,
  target            integer,
  slack_status      text,
  notes             text,
  error             text,
  started_at        timestamptz NOT NULL DEFAULT now(),
  finished_at       timestamptz
);
-- Run lock: at most one RUNNING row at any time.
-- A stale RUNNING row (older than run.lock_stale_hours) is marked FAILED with
-- stop_reason STALE_LOCK by LeadSearch before it takes the lock.
CREATE UNIQUE INDEX ux_ls_runs_single_running ON ls_runs ((true)) WHERE status = 'RUNNING';

-- ---------------------------------------------------------------
-- 2b. LeadSearch private working tables (Owner: LeadSearch only)
-- ---------------------------------------------------------------
CREATE TABLE ls_queries (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text          text NOT NULL,
  market        text NOT NULL,
  gl            text,
  hl            text,
  page          integer NOT NULL DEFAULT 1,
  executed_at   timestamptz,
  result_count  integer,
  new_domains   integer,
  run_id        uuid REFERENCES ls_runs(id),
  UNIQUE (text, gl, hl, page)
);

CREATE TABLE ls_candidates (
  domain           text PRIMARY KEY,        -- registered lowercase IDNA domain; every domain ever seen
  url              text NOT NULL,
  name_guess       text,
  source_query_id  bigint REFERENCES ls_queries(id),
  market           text,
  state            text NOT NULL
                     CHECK (state IN ('NEW', 'PREFILTERED_OUT', 'RETRY', 'VERIFIED', 'NEEDS_REVIEW', 'REJECTED')),
  state_reason     text,
  attempts         integer NOT NULL DEFAULT 0,
  discovered_at    timestamptz NOT NULL DEFAULT now(),
  last_attempt_at  timestamptz
);

CREATE TABLE ls_verifications (
  domain                text PRIMARY KEY REFERENCES ls_candidates(domain),
  status                text NOT NULL CHECK (status IN ('VERIFIED', 'NEEDS_REVIEW', 'REJECTED')),
  reasons_json          jsonb NOT NULL DEFAULT '[]'::jsonb,
  shopify_strength      text,
  shopify_evidence_json jsonb,
  app_level             text,
  app_evidence_json     jsonb,
  company_name          text,
  name_source           text,
  emails_json           jsonb,
  phones_json           jsonb,
  address               text,
  country               text,
  country_confidence    text,
  language              text,
  currency              text,
  socials_json          jsonb,
  contact_page_url      text,
  contact_form_url      text,
  anti_spam_regime      text,
  screening_status      text,
  screening_notes       text,
  pages_json            jsonb,
  firecrawl_requests    integer NOT NULL DEFAULT 0,
  run_id                uuid REFERENCES ls_runs(id),
  checked_at            timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE ls_api_usage (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider     text NOT NULL,               -- 'serper' | 'firecrawl'
  run_id       uuid REFERENCES ls_runs(id),
  ts           timestamptz NOT NULL DEFAULT now(),
  endpoint     text,
  ok           boolean NOT NULL,
  http_status  integer,
  note         text,
  credits      integer NOT NULL DEFAULT 0
);

-- ---------------------------------------------------------------
-- 3. leads  (client information)
--    Owners: LeadSearch writes facts + agent_approval;
--            review app writes human_* fields and manual edits.
-- ---------------------------------------------------------------
CREATE TABLE leads (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  -- identity
  domain             text NOT NULL UNIQUE,          -- normalized: lowercase, no scheme, no www
  site_url           text NOT NULL,
  company_name       text,
  contact_name       text,
  email              text,                          -- best single address (the mailer's recipient)
  email_type         text,                          -- type of that address, e.g. 'generic', 'personal'
  emails_json        jsonb NOT NULL DEFAULT '[]'::jsonb,   -- all found: [{"address":..., "type":...}]
  phone              text,                          -- best single number
  phones_json        jsonb NOT NULL DEFAULT '[]'::jsonb,
  address            text,
  country            text,                          -- ISO 3166-1 alpha-2 when known
  country_confidence text,
  language           text,                          -- ISO 639-1 when known
  currency           text,
  timezone           text,                          -- IANA, e.g. 'Europe/Berlin'; used for send window
  niche              text,
  contact_page_url   text,
  contact_form_url   text,
  socials            jsonb NOT NULL DEFAULT '{}'::jsonb,
  found_on           text,

  -- anti-spam screening (aid only, not legal advice)
  antispam_tag       text NOT NULL DEFAULT 'UNKNOWN_REVIEW'     -- screening status
                       CHECK (antispam_tag IN ('OPT_OUT_REGIME', 'CONDITIONAL', 'CONSENT_REQUIRED',
                                               'VARIES_REVIEW', 'UNKNOWN_REVIEW')),
  anti_spam_regime   text,                                      -- law name, e.g. 'CAN-SPAM Act'
  antispam_note      text,

  -- verification evidence (LeadSearch)
  is_shopify         boolean,
  has_mobile_app     boolean,
  app_signals        jsonb NOT NULL DEFAULT '[]'::jsonb,
  evidence           jsonb NOT NULL DEFAULT '{}'::jsonb,   -- keys: "shopify", "no_app", snippets (<=200 chars), URLs checked
  confidence         smallint CHECK (confidence BETWEEN 1 AND 10),
  source_query       text,
  source_run_id      uuid REFERENCES ls_runs(id),

  -- step 1: agent verdict (LeadSearch)
  agent_approval     text NOT NULL DEFAULT 'NEEDS_REVIEW'
                       CHECK (agent_approval IN ('VERIFIED', 'NEEDS_REVIEW', 'REJECTED')),
  agent_reason       text,                          -- review reasons, semicolon-separated

  -- step 2: human lead review (review app)
  human_approval     text NOT NULL DEFAULT 'PENDING'
                       CHECK (human_approval IN ('PENDING', 'APPROVED', 'REJECTED')),
  human_approved_by  uuid REFERENCES users(id),
  human_approved_at  timestamptz,
  human_note         text,

  -- lifecycle
  contacted          boolean NOT NULL DEFAULT false,   -- set by mailer after a successful send
  archived           boolean NOT NULL DEFAULT false,
  added_at           timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT chk_domain_lower CHECK (domain = lower(domain)),
  CONSTRAINT chk_approval_has_actor
    CHECK (human_approval = 'PENDING' OR (human_approved_by IS NOT NULL AND human_approved_at IS NOT NULL))
);
CREATE INDEX ix_leads_review_queue ON leads (added_at) WHERE agent_approval <> 'REJECTED' AND human_approval = 'PENDING';
CREATE INDEX ix_leads_approved     ON leads (added_at) WHERE human_approval = 'APPROVED';
CREATE TRIGGER trg_leads_updated BEFORE UPDATE ON leads
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------
-- 4. drafts  (email text; one row per version)
--    Owners: Drafter writes text/opener; review app edits text and approval.
-- ---------------------------------------------------------------
CREATE TABLE drafts (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  lead_id            uuid NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
  version            integer NOT NULL DEFAULT 1,

  subject            text NOT NULL,
  body_text          text NOT NULL,          -- plain text, WITHOUT the compliance footer (mailer appends it)
  ai_opener          text,                   -- the AI-written part, kept separately for review
  template_version   text,                   -- which template file/version was used
  ai_model           text,
  generation_note    text,                   -- errors / warnings from the drafter

  content_hash       text NOT NULL,          -- sha256(subject || body); set by trigger
  approved_hash      text,                   -- content_hash at approval time; set by trigger

  human_approval     text NOT NULL DEFAULT 'PENDING'
                       CHECK (human_approval IN ('PENDING', 'APPROVED', 'REJECTED')),
  human_approved_by  uuid REFERENCES users(id),
  human_approved_at  timestamptz,
  human_note         text,
  last_edited_by     uuid REFERENCES users(id),

  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),

  UNIQUE (lead_id, version),
  CONSTRAINT chk_draft_approval_has_actor
    CHECK (human_approval = 'PENDING' OR (human_approved_by IS NOT NULL AND human_approved_at IS NOT NULL))
);
-- At most one live (non-rejected) draft per lead.
CREATE UNIQUE INDEX ux_drafts_one_live_per_lead ON drafts (lead_id) WHERE human_approval <> 'REJECTED';
CREATE INDEX ix_drafts_review_queue ON drafts (created_at) WHERE human_approval = 'PENDING';

CREATE OR REPLACE FUNCTION drafts_guard() RETURNS trigger AS $$
BEGIN
  NEW.content_hash := encode(sha256(convert_to(NEW.subject || E'\n' || NEW.body_text, 'UTF8')), 'hex');

  IF TG_OP = 'UPDATE' THEN
    -- Any text change after approval resets the approval.
    IF NEW.content_hash IS DISTINCT FROM OLD.content_hash
       AND OLD.human_approval = 'APPROVED' AND NEW.human_approval = 'APPROVED' THEN
      NEW.human_approval    := 'PENDING';
      NEW.human_approved_by := NULL;
      NEW.human_approved_at := NULL;
      NEW.approved_hash     := NULL;
    END IF;
  END IF;

  IF NEW.human_approval = 'APPROVED' THEN
    NEW.approved_hash := NEW.content_hash;
  ELSE
    NEW.approved_hash := NULL;
  END IF;

  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_drafts_guard BEFORE INSERT OR UPDATE ON drafts
  FOR EACH ROW EXECUTE FUNCTION drafts_guard();

-- ---------------------------------------------------------------
-- 5. email_sends  (sending status + retries)  Owner: LeadMailer
--    One row per lead, created when an approved draft is queued.
-- ---------------------------------------------------------------
CREATE TABLE email_sends (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  lead_id             uuid NOT NULL UNIQUE REFERENCES leads(id),   -- one email per lead, no follow-ups
  draft_id            uuid NOT NULL REFERENCES drafts(id),
  to_email            text NOT NULL,                                -- snapshot at queue time
  send_key            text NOT NULL UNIQUE,                         -- sha256(lead_id|draft_id|approved_hash); idempotency

  status              text NOT NULL DEFAULT 'QUEUED'
                        CHECK (status IN ('QUEUED', 'SENDING', 'SENT', 'RETRY_WAIT',
                                          'NEEDS_HUMAN', 'BOUNCED', 'UNSUBSCRIBED', 'CANCELLED')),
  attempts            smallint NOT NULL DEFAULT 0,
  max_attempts        smallint NOT NULL DEFAULT 3,
  next_attempt_at     timestamptz,
  last_error          text,
  needs_human_reason  text,       -- e.g. UNCLEAR_OUTCOME, BOUNCE, MAX_ATTEMPTS

  gmail_message_id    text,
  gmail_thread_id     text,
  sent_from           text,
  sent_at             timestamptz,

  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT chk_attempts CHECK (attempts >= 0 AND attempts <= max_attempts)
);
CREATE INDEX ix_email_sends_due ON email_sends (next_attempt_at) WHERE status IN ('QUEUED', 'RETRY_WAIT');
CREATE TRIGGER trg_email_sends_updated BEFORE UPDATE ON email_sends
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------
-- 6. email_attempts  (per-try log; this is the "trail")  Owner: LeadMailer
-- ---------------------------------------------------------------
CREATE TABLE email_attempts (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  send_id          uuid NOT NULL REFERENCES email_sends(id) ON DELETE CASCADE,
  attempt_no       smallint NOT NULL,
  outcome          text NOT NULL CHECK (outcome IN ('SENT', 'FAILED_NOT_SENT', 'UNCLEAR')),
  error_code       text,
  error_message    text,
  gmail_message_id text,
  started_at       timestamptz NOT NULL DEFAULT now(),
  finished_at      timestamptz,
  UNIQUE (send_id, attempt_no)
);

-- ---------------------------------------------------------------
-- 7. suppressions  (bounces, unsubscribes, manual blocks)
-- ---------------------------------------------------------------
CREATE TABLE suppressions (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  kind        text NOT NULL CHECK (kind IN ('EMAIL', 'DOMAIN')),
  value       text NOT NULL,                     -- lowercase email or domain
  reason      text NOT NULL CHECK (reason IN ('UNSUBSCRIBE', 'BOUNCE', 'COMPLAINT', 'MANUAL')),
  source_send_id uuid REFERENCES email_sends(id),
  added_by    uuid REFERENCES users(id),
  note        text,
  added_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (kind, value),
  CONSTRAINT chk_supp_lower CHECK (value = lower(value))
);

-- ---------------------------------------------------------------
-- 8. audit_log  (who did what; append-only by convention)
-- ---------------------------------------------------------------
CREATE TABLE audit_log (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  actor_type  text NOT NULL CHECK (actor_type IN ('USER', 'LEADSEARCH', 'DRAFTER', 'MAILER', 'SYSTEM')),
  actor_id    uuid REFERENCES users(id),
  entity      text NOT NULL,                     -- 'lead' | 'draft' | 'email_send' | 'suppression' | ...
  entity_id   uuid NOT NULL,
  action      text NOT NULL,                     -- 'APPROVE' | 'REJECT' | 'EDIT' | 'REVOKE' | 'SEND' | ...
  details     jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_entity ON audit_log (entity, entity_id, created_at);

